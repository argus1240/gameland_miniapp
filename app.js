function pzCreateBoard() {
  const board = [];

  for (let r = 0; r < 8; r++) {
    board[r] = [];

    for (let c = 0; c < 8; c++) {
      let gem;

      do {
        gem = Math.floor(Math.random() * PZ_GEMS.length);
      } while (
        (c >= 2 && board[r][c - 1] === gem && board[r][c - 2] === gem) ||
        (r >= 2 && board[r - 1][c] === gem && board[r - 2][c] === gem)
      );

      board[r][c] = gem;
    }
  }

  return board;
}

function pzFindMatches(board) {
  const found = new Set();

  for (let r = 0; r < 8; r++) {
    let count = 1;

    for (let c = 1; c <= 8; c++) {
      if (c < 8 && board[r][c] !== null && board[r][c] === board[r][c - 1]) {
        count++;
      } else {
        if (count >= 3) {
          for (let k = c - count; k < c; k++) found.add(`${r},${k}`);
        }
        count = 1;
      }
    }
  }

  for (let c = 0; c < 8; c++) {
    let count = 1;

    for (let r = 1; r <= 8; r++) {
      if (r < 8 && board[r][c] !== null && board[r][c] === board[r - 1][c]) {
        count++;
      } else {
        if (count >= 3) {
          for (let k = r - count; k < r; k++) found.add(`${k},${c}`);
        }
        count = 1;
      }
    }
  }

  return [...found].map(key => key.split(",").map(Number));
}

